<?php

declare(strict_types=1);

namespace Adonyarik\ConsistentApi\Models;

use Adonyarik\ConsistentApi\Traits\CanFilter;
use Adonyarik\ConsistentApi\Traits\CanSort;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\Factory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

/**
 * Base Eloquent model of the API modules.
 *
 * Adds request-driven filtering (CanFilter) and sorting (CanSort), declared with #[Filterable] /
 * #[Sortable] attributes, plus join helpers for scopes, factory lookup by class name and a page size
 * of 10. ConsistentController::indexLogic() relies on these methods, and models generated by
 * consistent:create extend this class.
 *
 * @package Adonyarik\ConsistentApi\Models
 * @author Yaroslav Tyrchenko <tyrchenkoy@gmail.com>
 * @since 1.0.0
 */
class ConsistentModel extends Model
{
    use CanFilter, CanSort;
    use HasFactory {
        HasFactory::newFactory as protected newFactoryFromModelSettings;
    }

    /**
     * Page size of paginate() when the request has no perpage, instead of Eloquent's 15.
     *
     * @var int
     */
    protected $perPage = 10;

    /**
     * Resolves the model factory: the model's own settings first, then by the model's class name.
     *
     * HasFactory::factory() calls it first. A static $factory property or a #[UseFactory] attribute on
     * the model wins, as in any Laravel model. Without them, Database\Factories\{Model}Factory is used:
     * module models live outside App\Models, where Laravel's own convention would look for
     * Database\Factories\Modules\Posts\Models\PostFactory. That factory is told which model it creates,
     * as Laravel does for #[UseFactory], unless it names its model itself ($model or #[UseModel]); a
     * factory of a module model has no other way to find it. The model name is set per factory class, so
     * two modules with a model of the same short name should point to their own factories with
     * #[UseFactory]. When the class does not exist either, null lets Laravel fall back to
     * Factory::factoryForModel().
     *
     * @return Factory|null A new factory instance, null when the model names none and Database\Factories\{Model}Factory does not exist
     *
     * @see HasFactory::factory()
     * @see HasFactory::newFactory()
     */
    protected static function newFactory(): ?Factory
    {
        $factory = static::newFactoryFromModelSettings();

        if ($factory !== null) {
            return $factory;
        }

        $modelName = class_basename(static::class);

        $factoryClass = "Database\\Factories\\{$modelName}Factory";

        if (class_exists($factoryClass)) {
            $factory = $factoryClass::new();
            $factory->guessModelNamesUsing(fn () => static::class);

            return $factory;
        }

        return null;
    }

    /**
     * Inner join of $table, skipped when the query already joins it.
     *
     * A helper for the model's scopes. It skips the join when any join of the same table is already
     * on the query, see addJoinOnce() for the rules.
     *
     * @param  Builder  $query  Query of this model, usually the scope's $query
     * @param  string  $table  Table to join, compared as written with the joined tables
     * @param  string  $first  First column of the on condition
     * @param  string  $operator  Comparison operator of the on condition
     * @param  string  $second  Second column of the on condition
     *
     * @return Builder The same query, with the join added unless the table was already joined
     *
     * @see ConsistentModel::addJoinOnce()
     */
    protected function joinOnce(Builder $query, string $table, string $first, string $operator, string $second): Builder
    {
        return $this->addJoinOnce($query, 'inner', $table, $first, $operator, $second);
    }

    /**
     * Left join of $table, skipped when the query already joins it.
     *
     * A helper for the model's scopes. It skips the join when any join of the same table is already
     * on the query, see addJoinOnce() for the rules.
     *
     * @param  Builder  $query  Query of this model, usually the scope's $query
     * @param  string  $table  Table to join, compared as written with the joined tables
     * @param  string  $first  First column of the on condition
     * @param  string  $operator  Comparison operator of the on condition
     * @param  string  $second  Second column of the on condition
     *
     * @return Builder The same query, with the join added unless the table was already joined
     *
     * @see ConsistentModel::addJoinOnce()
     */
    protected function leftJoinOnce(Builder $query, string $table, string $first, string $operator, string $second): Builder
    {
        return $this->addJoinOnce($query, 'left', $table, $first, $operator, $second);
    }

    /**
     * Right join of $table, skipped when the query already joins it.
     *
     * A helper for the model's scopes. It skips the join when any join of the same table is already
     * on the query, see addJoinOnce() for the rules.
     *
     * @param  Builder  $query  Query of this model, usually the scope's $query
     * @param  string  $table  Table to join, compared as written with the joined tables
     * @param  string  $first  First column of the on condition
     * @param  string  $operator  Comparison operator of the on condition
     * @param  string  $second  Second column of the on condition
     *
     * @return Builder The same query, with the join added unless the table was already joined
     *
     * @see ConsistentModel::addJoinOnce()
     */
    protected function rightJoinOnce(Builder $query, string $table, string $first, string $operator, string $second): Builder
    {
        return $this->addJoinOnce($query, 'right', $table, $first, $operator, $second);
    }

    /**
     * Adds the join unless the table is already joined, whatever the type of that join.
     *
     * The first join of a table wins: leftJoinOnce() after joinOnce() of the same table keeps the inner join.
     * This lets several scopes join the same table without a duplicate table error.
     * The table is compared as written, so 'users as u' and 'users' are different joins.
     * The on condition is a single column comparison; a closure is not supported.
     *
     * @param  Builder  $query  Query to add the join to
     * @param  string  $type  Join type passed to Query\Builder::join(): inner, left or right
     * @param  string  $table  Table to join
     * @param  string  $first  First column of the on condition
     * @param  string  $operator  Comparison operator of the on condition
     * @param  string  $second  Second column of the on condition
     *
     * @return Builder The same query, with the join added unless the table was already joined
     */
    private function addJoinOnce(Builder $query, string $type, string $table, string $first, string $operator, string $second): Builder
    {
        foreach ($query->getQuery()->joins ?? [] as $join) {
            if ($join->table === $table) {
                return $query;
            }
        }

        return $query->join($table, $first, $operator, $second, $type);
    }

    /**
     * Column names of the model's table.
     *
     * Reads the schema of the model's own connection on every call (one query), so the list follows the
     * actual table, not $fillable or the attribute declarations, and a model with $connection reads its
     * own database rather than the default one.
     *
     * @return list<string> Column names in table order
     */
    public function getAllColumns(): array
    {
        return $this->getConnection()->getSchemaBuilder()->getColumnListing($this->getTable());
    }
}
