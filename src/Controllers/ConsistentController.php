<?php

declare(strict_types=1);

namespace Adonyarik\ConsistentApi\Controllers;

use Adonyarik\ConsistentApi\Contracts\WithoutPaginationModelContract;
use Adonyarik\ConsistentApi\Models\ConsistentModel;
use Adonyarik\ConsistentApi\Requests\BaseSearchRequest;
use Adonyarik\ConsistentApi\Responses\PaginatedJsonResponse;
use Adonyarik\ConsistentApi\Support\AccessResolver;
use Adonyarik\ConsistentApi\Traits\CanFilter;
use Adonyarik\ConsistentApi\Traits\CanSort;
use Illuminate\Auth\Access\AuthorizationException;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\QueryException;
use Illuminate\Foundation\Auth\Access\AuthorizesRequests;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Foundation\Validation\ValidatesRequests;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Resources\Json\JsonResource;
use Illuminate\Routing\Controller as IlluminateController;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\Response;
use Illuminate\Validation\ValidationException;
use LogicException;
use Symfony\Component\HttpKernel\Exception\HttpException;

/**
 * Base API controller with the CRUD logic of a module.
 *
 * Controllers generated by consistent:create extend it and call indexLogic(), selectLogic(), storeLogic(),
 * updateLogic() and destroyLogic() from their actions. Responses use the resource bound to the current
 * action in $resourceClasses, or $resourceClass, and relations listed in $relationFunctions are eager
 * loaded. The index filters, sorts and paginates by the model's #[Filterable] / #[Sortable] declarations
 * and the access groups of the request's route. Every *Logic() method authorizes its action through
 * authorizeAction() first, which uses the model's policy when there is one. Protected hooks let a subclass
 * or a trait shared by several controllers change the logic without rewriting it: indexQuery() scopes the
 * index query, beforeStore() and beforeUpdate() adjust the model before it is saved. Like a controller of a
 * Laravel application, it extends Illuminate\Routing\Controller with AuthorizesRequests and ValidatesRequests.
 *
 * @package Adonyarik\ConsistentApi\Controllers
 * @author Yaroslav Tyrchenko <tyrchenkoy@gmail.com>
 * @since 1.0.0
 */
class ConsistentController extends IlluminateController
{
    use AuthorizesRequests, ValidatesRequests;

    /**
     * Resource of every action that has no entry in $resourceClasses.
     *
     * Defaults to JsonResource, which returns every visible attribute of the model.
     *
     * @var class-string<JsonResource>
     */
    protected string $resourceClass = JsonResource::class;

    /**
     * Resource per controller method; methods not listed use $resourceClass.
     *
     * @var array<string, class-string<JsonResource>>
     */
    protected array $resourceClasses = [];

    /**
     * Controller method the router is calling, recorded by callAction(); null outside a routed call.
     */
    private ?string $currentAction = null;

    /**
     * Relations eager loaded on every model the *Logic() methods return.
     *
     * @var list<string>
     */
    protected array $relationFunctions = [];

    /**
     * Remembers the action being called, then runs it.
     *
     * Laravel's ControllerDispatcher calls it for every route action. The stored method name lets
     * resourceClassFor() pick the action's resource from $resourceClasses. A subclass that overrides it
     * must call parent::callAction(), otherwise every action falls back to $resourceClass.
     *
     * @param  string  $method  Controller method of the route
     * @param  array<int|string, mixed>  $parameters  Route parameters and injected dependencies
     *
     * @return mixed Whatever the action returns
     *
     * @see ConsistentController::resourceClassFor()
     */
    public function callAction($method, $parameters)
    {
        $this->currentAction = $method;

        return parent::callAction($method, $parameters);
    }

    /**
     * Resource class for a controller method.
     *
     * Returns the method's entry in $resourceClasses, or $resourceClass when it has none. Without an
     * argument it takes the action recorded by callAction(); outside a routed call, for example when a test
     * calls a method directly, there is none and $resourceClass is used.
     *
     * @param  string|null  $method  Controller method; null for the action being called
     *
     * @return class-string<JsonResource> Resource class to wrap the models in
     */
    protected function resourceClassFor(?string $method = null): string
    {
        $method ??= $this->currentAction;

        if ($method !== null && isset($this->resourceClasses[$method])) {
            return $this->resourceClasses[$method];
        }

        return $this->resourceClass;
    }

    /**
     * Authorizes an action before a *Logic() method runs it.
     *
     * Called with viewAny and the model class by indexLogic(), view by selectLogic(), create and the model
     * class by storeLogic(), update by updateLogic() and delete by destroyLogic(). When a policy is
     * registered or discovered for the model, the ability is checked with $this->authorize(), which answers
     * 403 when the policy denies it (or lacks the method); without a policy every action is allowed, so
     * access depends on the route middleware alone. Override it to authorize differently, for example with
     * Gate abilities or checks of your own, or with an empty body to switch authorization off.
     *
     * @param  string  $ability  viewAny, view, create, update or delete
     * @param  Model|class-string<Model>  $subject  Model instance, or its class for viewAny and create
     *
     * @throws AuthorizationException When the policy denies the ability
     */
    protected function authorizeAction(string $ability, Model|string $subject): void
    {
        if (Gate::getPolicyFor($subject) !== null) {
            $this->authorize($ability, $subject);
        }
    }

    /**
     * Base query of indexLogic(), before the requested filters and sorts.
     *
     * buildFilterSortQuery() passes it $model::query() and applies the filter() and sort() scopes to what it
     * returns, so constraints added here hold whatever the client sends: filters only narrow the result,
     * and the pagination meta counts only the rows the query allows. Override it to scope the list, for
     * example to the records of the current user in a trait shared by the controllers of personal modules,
     * or to add withCount() or select(). Qualify the columns you name ($query->qualifyColumn('user_id')),
     * since scopes may join other tables, and wrap orWhere() conditions in where(fn (Builder $query) => ...),
     * or the requested filters attach to the last of them only. An orderBy() added here comes before the
     * requested sorts. The default returns the query unchanged.
     *
     * @param  Builder<ConsistentModel>  $query  New query of the listed model
     * @param  BaseSearchRequest  $request  Search request of the index action
     *
     * @return Builder<ConsistentModel> The query to filter, sort and paginate
     *
     * @see ConsistentController::buildFilterSortQuery()
     */
    protected function indexQuery(Builder $query, BaseSearchRequest $request): Builder
    {
        return $query;
    }

    /**
     * Adjusts a new model in storeLogic() right before it is saved.
     *
     * Runs after authorization and after the model is filled with $request->validated(), so attributes set
     * here take precedence over the client's input: the owner ($model->user()->associate($request->user())),
     * defaults, values derived from the input. Unlike attributes set on the instance before storeLogic() is
     * called, it applies to every action of the controller that calls storeLogic(), which suits a trait
     * shared by several controllers. Throw an HttpException to refuse the write. The default does nothing.
     *
     * @param  FormRequest  $request  Store request of the action
     * @param  Model  $model  New model, filled and not saved yet
     *
     * @see ConsistentController::storeLogic()
     */
    protected function beforeStore(FormRequest $request, Model $model): void {}

    /**
     * Adjusts the model in updateLogic() right before it is saved.
     *
     * Runs after authorization and after the model is filled with $request->validated(), so attributes set
     * here take precedence over the client's input, and isDirty() / getOriginal() tell what the request
     * changes. Throw an HttpException to refuse the write. The default does nothing.
     *
     * @param  FormRequest  $request  Update request of the action
     * @param  Model  $model  Route-bound model, filled and not saved yet
     *
     * @see ConsistentController::updateLogic()
     */
    protected function beforeUpdate(FormRequest $request, Model $model): void {}

    /**
     * Lists models filtered, sorted and paginated by the search request.
     *
     * Authorizes viewAny, takes the validated input except id, resolves the access groups of the request's
     * route and builds the query with buildFilterSortQuery(), which starts from indexQuery() and answers 422
     * for a column or operator the route may not use. The rows are ordered by the primary key after the requested sorts, so pages
     * never overlap or skip rows. Returns page `page` of perpage items (the model's $perPage when absent)
     * as a PaginatedJsonResponse. A model implementing WithoutPaginationModelContract returns the rows
     * under the data container without meta when the request has paginate=false, at most
     * consistentapi.pagination.unpaginated_limit of them. Only validated values are read, never the raw
     * request input. A filter value the database cannot compare with its column (abc for an integer
     * column on PostgreSQL) answers 422 instead of a server error.
     *
     * @param  BaseSearchRequest  $request  Search request of the index action
     * @param  ConsistentModel  $model  Instance of the listed model; only its class and declarations are used
     *
     * @return JsonResponse A PaginatedJsonResponse, or the items without pagination meta
     *
     * @throws ValidationException 422 for a column or operator the route may not filter or sort by, or a value of the wrong shape or type
     * @throws AuthorizationException When the policy denies viewAny
     *
     * @see ConsistentController::indexQuery()
     * @see ConsistentController::buildFilterSortQuery()
     * @see AccessResolver::forRoute()
     * @see PaginatedJsonResponse
     * @see WithoutPaginationModelContract
     */
    public function indexLogic(BaseSearchRequest $request, ConsistentModel $model): JsonResponse
    {
        $this->authorizeAction('viewAny', $model::class);

        $filters = $request->safe()->except('id');

        $accesses = app(AccessResolver::class)->forRoute($request->route());

        // The primary key breaks ties, so LIMIT / OFFSET pages are stable
        $query = $this->buildFilterSortQuery($request, $filters, $model, $accesses)->orderBy($model->getQualifiedKeyName());

        try {
            if ($model instanceof WithoutPaginationModelContract
                && ! filter_var($filters['paginate'] ?? true, FILTER_VALIDATE_BOOLEAN)) {
                $limit = config('consistentapi.pagination.unpaginated_limit', 1000);

                return new JsonResponse([
                    config('consistentapi.pagination.data_container_name', 'items') => $this->resourceClassFor()::collection(
                        $query->when($limit !== null, fn (Builder $query) => $query->limit((int) $limit))->get()
                    )->resolve($request),
                ]);
            }

            $items = $query->paginate(
                isset($filters['perpage']) ? (int) $filters['perpage'] : null,
                page: isset($filters['page']) ? (int) $filters['page'] : null,
            );
        } catch (QueryException $exception) {
            // SQLSTATE class 22 is a data exception: a value the column type cannot take
            if (str_starts_with((string) ($exception->errorInfo[0] ?? $exception->getCode()), '22')) {
                $this->failValidation('filter', 'A filter value does not match the type of its column.');
            }

            throw $exception;
        }

        return new PaginatedJsonResponse(
            $items,
            $this->resourceClassFor()
        );
    }

    /**
     * Returns one model through the action's resource.
     *
     * Used by show(): answers 404 for a model that does not exist, authorizes view, eager loads
     * $relationFunctions on the route-bound model and wraps it in the resource of the current action.
     *
     * @param  Model  $model  Route-bound model
     *
     * @return JsonResource The model in the action's resource
     *
     * @throws HttpException 404 when the model does not exist
     * @throws AuthorizationException When the policy denies view
     *
     * @see ConsistentController::ensureExists()
     * @see ConsistentController::loadRelations()
     * @see ConsistentController::resourceClassFor()
     */
    public function selectLogic(Model $model): JsonResource
    {
        $this->ensureExists($model);
        $this->authorizeAction('view', $model);

        return new ($this->resourceClassFor())($this->loadRelations($model));
    }

    /**
     * Creates a model from the validated input and answers 201 Created.
     *
     * Authorizes create, then fills the given instance with $request->validated(), runs beforeStore() and
     * saves it. Only fillable attributes are mass-assigned, and attributes set on the instance beforehand
     * are kept, so the caller can set what must not come from the client: $post = new Post;
     * $post->author()->associate($request->user()); return $this->storeLogic($request, $post). The new
     * model is returned in the action's resource with $relationFunctions loaded. A save cancelled by a model
     * event answers 409.
     *
     * @param  FormRequest  $request  Store request of the action
     * @param  Model  $model  New, unsaved instance of the model to create
     *
     * @return JsonResponse The created model in the action's resource, status 201
     *
     * @throws AuthorizationException When the policy denies create
     * @throws HttpException 409 when a creating or saving listener cancels the save
     * @throws LogicException When the model already exists
     *
     * @see ConsistentController::beforeStore()
     * @see ConsistentController::writeRefused()
     */
    public function storeLogic(FormRequest $request, Model $model): JsonResponse
    {
        if ($model->exists) {
            throw new LogicException(sprintf('storeLogic() creates models; it was given an existing %s.', $model::class));
        }

        $this->authorizeAction('create', $model::class);

        $model->fill($request->validated());
        $this->beforeStore($request, $model);

        if (! $model->save()) {
            $this->writeRefused('The record was not created.');
        }

        return (new ($this->resourceClassFor())($this->loadRelations($model)))
            ->response($request)
            ->setStatusCode(JsonResponse::HTTP_CREATED);
    }

    /**
     * Updates the route-bound model with the validated input.
     *
     * Answers 404 for a model that does not exist, authorizes update, fills it with $request->validated()
     * (fillable attributes only), runs beforeUpdate() and saves it, loads $relationFunctions and returns the
     * model in the action's resource with status 200. A save cancelled by a model event answers 409, so the
     * client never sees values that were not stored.
     *
     * @param  FormRequest  $request  Update request of the action
     * @param  Model  $model  Route-bound model to update
     *
     * @return JsonResource The updated model in the action's resource
     *
     * @throws HttpException 404 when the model does not exist, 409 when an updating or saving listener cancels the save
     * @throws AuthorizationException When the policy denies update
     *
     * @see ConsistentController::ensureExists()
     * @see ConsistentController::beforeUpdate()
     * @see ConsistentController::writeRefused()
     */
    public function updateLogic(FormRequest $request, Model $model): JsonResource
    {
        $this->ensureExists($model);
        $this->authorizeAction('update', $model);

        $model->fill($request->validated());
        $this->beforeUpdate($request, $model);

        if (! $model->save()) {
            $this->writeRefused('The record was not updated.');
        }

        return new ($this->resourceClassFor())($this->loadRelations($model));
    }

    /**
     * Deletes the model and answers 204 No Content.
     *
     * Answers 404 for a model that does not exist, authorizes delete and calls delete(), so soft deletes
     * and model events work as the model defines them. A deletion cancelled by a deleting listener answers
     * 409 instead of 204.
     *
     * @param  Model  $model  Route-bound model to delete
     *
     * @return JsonResponse Empty response with status 204
     *
     * @throws HttpException 404 when the model does not exist, 409 when a deleting listener cancels the deletion
     * @throws AuthorizationException When the policy denies delete
     *
     * @see ConsistentController::ensureExists()
     * @see ConsistentController::writeRefused()
     */
    public function destroyLogic(Model $model): JsonResponse
    {
        $this->ensureExists($model);
        $this->authorizeAction('delete', $model);

        if ($model->delete() === false) {
            $this->writeRefused('The record was not deleted.');
        }

        return new JsonResponse(status: JsonResponse::HTTP_NO_CONTENT);
    }

    /**
     * Answers 404 for a model that is not stored.
     *
     * A route without SubstituteBindings (consistentapi.middlewares without api, for example) hands the
     * action an empty instance instead of answering 404; updating it would insert a row and deleting it
     * would answer 204 for nothing.
     *
     * @param  Model  $model  Route-bound model
     *
     * @throws HttpException 404 when the model does not exist
     */
    protected function ensureExists(Model $model): void
    {
        if (! $model->exists) {
            throw new HttpException(JsonResponse::HTTP_NOT_FOUND, 'Not found.');
        }
    }

    /**
     * Ends a write that a model event cancelled with 409 Conflict.
     *
     * Eloquent's save() and delete() return false when a creating, updating, saving or deleting listener
     * returns false. Override it to answer differently.
     *
     * @param  string  $message  Message of the error response
     *
     * @throws HttpException Always, with status 409
     */
    protected function writeRefused(string $message): never
    {
        throw new HttpException(JsonResponse::HTTP_CONFLICT, $message);
    }

    /**
     * Eager loads $relationFunctions on a model.
     *
     * One load() call for all relations; nothing happens when the controller lists none.
     *
     * @param  Model  $model  Model to return from an action
     *
     * @return Model The same model with the relations loaded
     */
    private function loadRelations(Model $model): Model
    {
        if ($this->relationFunctions !== []) {
            $model->load($this->relationFunctions);
        }

        return $model;
    }

    /**
     * Builds the index query from sort and filter input, rejecting what the route may not use.
     *
     * Every sort column, sort direction, filter column, nested filter key and filter value is checked; the
     * first violation ends the request with 422 and a message keyed by the input path (sort.title,
     * filter.email, filter.price.like). Columns and operators must be in the model's allowed lists for the
     * accesses, operators must also be enabled in consistentapi.filters.operators, and a plain list of
     * filter values counts as the `in` key. A direction is asc or desc. A column declared with operators
     * takes operators only, not a scalar value, and each operator value must have the shape
     * filterValueError() accepts: a single value, a list for `in` / `not_in`, a date for `from` / `to`, a
     * boolean for `null`. Empty values mean "not set" and are not checked. The checks do not depend on the
     * search request's rules, so the query never runs with unchecked input. The query starts from
     * indexQuery(), valid input is applied through the sort() and filter() scopes, and $relationFunctions
     * are eager loaded.
     *
     * @param  BaseSearchRequest  $request  Search request of the index action, passed to indexQuery()
     * @param  array<string, mixed>  $filters  Validated search input with sort and filter keys
     * @param  ConsistentModel  $model  Instance of the listed model
     * @param  list<string>  $accesses  Accesses of the request's route; columns restricted to other groups count as unknown
     *
     * @return Builder<ConsistentModel> The query to paginate or get
     *
     * @throws ValidationException 422 for a column or operator the accesses do not allow, or a value of the wrong shape
     *
     * @see ConsistentController::indexQuery()
     * @see CanSort::getAllowedSorts()
     * @see CanSort::scopeSort()
     * @see CanFilter::getAllowedFilters()
     * @see CanFilter::getAllowedFilterKeys()
     * @see CanFilter::filterValueError()
     * @see CanFilter::scopeFilter()
     * @see ConsistentController::failValidation()
     */
    private function buildFilterSortQuery(BaseSearchRequest $request, array $filters, ConsistentModel $model, array $accesses): Builder
    {
        $query = $this->indexQuery($model::query(), $request);

        if (is_array($filters['sort'] ?? null)) {
            $allowedSorts = $model->getAllowedSorts($accesses);

            if ($allowedSorts === []) {
                $this->failValidation('sort', 'Sorting on this object is not allowed.');
            }

            foreach ($filters['sort'] as $column => $direction) {
                if (! in_array($column, $allowedSorts, true)) {
                    $this->failValidation("sort.$column", "Sorting by $column is not allowed.");
                }

                // An empty direction means the column was not set
                if ($direction !== null && $direction !== '' && ! in_array($direction, ['asc', 'desc'], true)) {
                    $this->failValidation("sort.$column", "Sorting by $column takes asc or desc.");
                }
            }

            $query = $query->sort($filters['sort'], $accesses);
        }

        if (is_array($filters['filter'] ?? null)) {
            $allowedFilters = $model->getAllowedFilters($accesses);
            $enabledOperators = (array) config('consistentapi.filters.operators', []);

            if ($allowedFilters === []) {
                $this->failValidation('filter', 'Filtering on this object is not allowed.');
            }

            foreach ($filters['filter'] as $column => $value) {
                if (! in_array($column, $allowedFilters, true)) {
                    $this->failValidation("filter.$column", "Filtering by $column is not allowed.");
                }

                $allowedKeys = $model->getAllowedFilterKeys($column, $accesses);

                if (! is_array($value)) {
                    // An empty value means the filter was not set
                    if ($allowedKeys !== null && ! $model->isEmptyFilterValue($value)) {
                        $this->failValidation("filter.$column", "Filtering by $column requires an operator.");
                    }

                    continue;
                }

                if ($allowedKeys === null) {
                    $this->failValidation("filter.$column", "Nested filtering by $column is not allowed.");
                }

                // Operators switched off in config are not allowed, whatever the model declares
                $allowedKeys = array_values(array_intersect($allowedKeys, $enabledOperators));

                // A plain list of values is an `in` filter
                $operators = array_is_list($value) ? ['in' => $value] : $value;

                foreach ($operators as $operator => $operand) {
                    if (! in_array($operator, $allowedKeys, true)) {
                        $this->failValidation("filter.$column.$operator", "Filtering by $column.$operator is not allowed.");
                    }

                    $error = $model->isEmptyFilterValue($operand) ? null : $model->filterValueError($operator, $operand);

                    if ($error !== null) {
                        $this->failValidation("filter.$column.$operator", "Filtering by $column.$operator $error.");
                    }
                }
            }

            $query = $query->filter($filters['filter'], $accesses);
        }

        $query->with($this->relationFunctions);

        return $query;
    }

    /**
     * Ends the request with a 422 validation error for one input key.
     *
     * Throws a ValidationException whose response has the shape Laravel gives a failed form request:
     * {"message": the error, "errors": {key: [the error]}}, so clients handle both the same way. The key
     * and the message repeat names from the input, so the JSON is encoded with < > & ' " as <-style
     * escapes: the body never carries markup from the input, while a JSON decoder still reads the original
     * text.
     *
     * @param  string  $key  Input path the error is reported under, such as filter.email
     * @param  string  $message  Error message
     *
     * @throws ValidationException Always, carrying the 422 JSON response
     */
    private function failValidation(string $key, string $message): never
    {
        $exception = ValidationException::withMessages([$key => [$message]]);

        $exception->response = Response::json([
            'message' => $message,
            'errors' => [
                $key => [$message],
            ],
        ], JsonResponse::HTTP_UNPROCESSABLE_ENTITY, [], JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT);

        throw $exception;
    }
}
